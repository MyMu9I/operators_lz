n= int(input('Введите число n: '))  #Ввод числа n
A = 0   #A счётчик количества операций
while n!=0:
    if n%3==0:  #Если число делится на 3 нацело
            n= n-3
            A+=1
    elif n%3==1:   #Если число делится на 3 и дает остаток 1
        n= n-1
        A+=1 
    elif n%3==2:     #Если число делиться на 3 и дает остаток 2
        n=n-2
        A+=1
print(A)      #Вывод счетчика кол-ва операций